/** Netlify-style redirect rules for static hosts (copied to dist via public/). */
import fs from 'node:fs';
import path from 'node:path';
import { PATH_REDIRECTS } from './redirects.mjs';
import { CHECKOUT_PATH_REDIRECTS } from '../src/config/checkout-redirects.mjs';
import { SITE_URL } from '../src/config/site-url.mjs';

const lines = ['# Generated by scripts/generate-static-redirects.mjs. Do not edit.'];
for (const [from, to] of PATH_REDIRECTS.entries()) {
  lines.push(`${from}  ${to}  301`);
}
for (const [from, to] of CHECKOUT_PATH_REDIRECTS.entries()) {
  lines.push(`${from}  ${to}  302`);
}

const out = path.join('public', '_redirects');
fs.writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length - 1} redirect rules → ${out}`);

const robots = `User-agent: *
Allow: /
Disallow: /go/
Disallow: /es/go/
Disallow: /de/go/
Disallow: /fr/go/

Sitemap: ${SITE_URL}/sitemap.xml
`;
fs.writeFileSync(path.join('public', 'robots.txt'), robots);
console.log(`Wrote public/robots.txt → Sitemap: ${SITE_URL}/sitemap.xml`);

/** Fallback pages when a host serves files instead of `_redirects`. Hover still shows `/go/…`. */
function escapeHtml(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

let checkoutPages = 0;
for (const [from, to] of CHECKOUT_PATH_REDIRECTS.entries()) {
  if (!from.endsWith('/')) continue;
  const dir = path.join('public', from);
  fs.mkdirSync(dir, { recursive: true });
  const href = escapeHtml(to);
  const jsUrl = JSON.stringify(to);
  fs.writeFileSync(
    path.join(dir, 'index.html'),
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="robots" content="noindex, nofollow">
<title>Continue</title>
<meta http-equiv="refresh" content="0;url=${href}">
<script>var dest=${jsUrl};var extra=location.search?location.search.slice(1):"";if(extra)dest+=(dest.indexOf("?")>=0?"&":"?")+extra;location.replace(dest);</script>
</head>
<body></body>
</html>
`,
  );
  checkoutPages += 1;
}
console.log(`Wrote ${checkoutPages} checkout redirect pages → public/go/`);
